def explain_standard_exit_code(exit_code):
    """查询标准 Windows/MSI 退出码的原因和处理建议。

    参数：exit_code 是外部进程返回的整数退出码。
    返回值：命中标准码时返回 ``(原因, 建议)`` 元组；未定义、厂商私有或无效代码返回 None。
    副作用：无。调用方必须始终保留原退出码，不能把未命中的数字误解释为 Windows 错误。
    """
    try:
        normalized_code = int(exit_code)
    except (TypeError, ValueError):
        return None
    return _STANDARD_EXIT_CODE_DETAILS.get(normalized_code)
