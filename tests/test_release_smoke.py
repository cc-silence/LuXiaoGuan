"""Release validation must not collect the runtime data produced by its own smoke tests."""
from pathlib import Path
import tempfile
import unittest
from scripts.release_smoke import verify_package_smoke


class ReleaseSmokeTests(unittest.TestCase):
    def exercise(self,fail=False):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory);package=root/"delivery";stage=root/"stage";stage.mkdir()
            (package/"resources").mkdir(parents=True)
            (package/"LuXiaoGuan.exe").write_bytes(b"app")
            (package/"resources/RouterManagerUpdateWorker.exe").write_bytes(b"worker")
            calls=[]
            def run(args,log,env,timeout):
                executable=Path(args[0]);calls.append((args,env.copy()))
                self.assertFalse(executable.is_relative_to(package))
                self.assertFalse(Path(env["ROUTERMANAGER_USER_CONFIG_DIR"]).is_relative_to(package))
                self.assertEqual(env["QT_QPA_PLATFORM"],"offscreen")
                if args[1]=="--smoke-test":
                    (executable.parent/"RouterManagerData").mkdir()
                    (executable.parent/"RouterManagerData/history.sqlite").write_bytes(b"generated by smoke")
                    if fail:raise RuntimeError("smoke failed")
                if args[1]=="--local-gpo-firewall":Path(args[3]).write_text('{"success":true}',encoding="utf-8")
            if fail:
                with self.assertRaisesRegex(RuntimeError,"smoke failed"):
                    verify_package_smoke(package,stage,{},run)
            else:
                self.assertEqual(len(verify_package_smoke(package,stage,{},run)),5)
                self.assertEqual(len(calls),5)
            self.assertFalse((package/"RouterManagerData").exists())
            self.assertEqual((package/"LuXiaoGuan.exe").read_bytes(),b"app")
            self.assertFalse(Path(calls[0][0][0]).exists())

    def test_runtime_data_remains_outside_delivery_and_temp_copy_is_reclaimed(self):self.exercise()
    def test_failed_smoke_preserves_delivery_and_reclaims_copy(self):self.exercise(True)


if __name__=="__main__":unittest.main()
